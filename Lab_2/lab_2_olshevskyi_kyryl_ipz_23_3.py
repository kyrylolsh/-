def build_best_model(input_dim):
    return nn.Sequential(
        nn.Linear(input_dim, 128),
        nn.LeakyReLU(negative_slope=0.1),
        nn.Linear(128, 64),
        nn.LeakyReLU(negative_slope=0.1),
        nn.Linear(64, 32),
        nn.LeakyReLU(negative_slope=0.1),
        nn.Linear(32, 1)
    )

# Функція для проведення експерименту
def run_experiment(exp_name, optimizer_cls, opt_kwargs, epochs):
    model = build_best_model(X_train_t.shape[1])
    optimizer = optimizer_cls(model.parameters(), **opt_kwargs)
    loss_fn = nn.MSELoss()
    writer = SummaryWriter(log_dir=os.path.join(RUNS_DIR, exp_name))

    train_losses, val_losses = [], []

    for epoch in range(epochs):
        model.train()
        optimizer.zero_grad()
        y_pred = model(X_train_t)
        loss = loss_fn(y_pred, y_train_t)
        loss.backward()
        optimizer.step()
        train_losses.append(loss.item())

        model.eval()
        with torch.no_grad():
            val_loss = loss_fn(model(X_val_t), y_val_t).item()
        val_losses.append(val_loss)

        writer.add_scalar("Loss/train", loss.item(), epoch)
        writer.add_scalar("Loss/val", val_loss, epoch)

    writer.close()

    # Оцінка на тестовій вибірці
    model.eval()
    with torch.no_grad():
        test_preds = model(X_test_t).numpy()

    mse = mean_squared_error(y_test_true, test_preds)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(y_test_true, test_preds)
    r2 = r2_score(y_test_true, test_preds)

    print(f"=== {exp_name} ===")
    print(f"MSE: {mse:.4f} | RMSE: {rmse:.4f} | MAE: {mae:.4f} | R²: {r2:.4f}\n")
    return model, {"mse": mse, "rmse": rmse, "mae": mae, "r2": r2}

